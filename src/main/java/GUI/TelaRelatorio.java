    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String selecionado = (String) comboRelatorio.getSelectedItem(); 

            if (selecionado != null && selecionado.endsWith("%")) {
                selecionado = selecionado.replace("%", ""); 
                try {
                    double porcentagem = Double.parseDouble(selecionado);
                    double fator = porcentagem / 100.0;
                    aplicarZoom(fator); 
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Zoom inválido.");
                }
            }

       
    }//GEN-LAST:event_jButton1ActionPerformed

